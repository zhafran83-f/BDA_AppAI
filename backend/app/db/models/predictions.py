"""Append-only prediction history; no raw inputs, user filenames, or profiles.

predicted_at must be supplied as a timezone-aware application timestamp.
UUIDs are generated by the application at INSERT, not by a server extension.
model_version identifies the bundle; artifact_sha256 identifies individual files.
"""

from datetime import datetime
from uuid import UUID, uuid4

from sqlalchemy import (
    BigInteger, CheckConstraint, DateTime, Double, Index, Integer,
    SmallInteger, Text, func, text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column


from ..base import Base


class PredictionFields:
    id: Mapped[UUID] = mapped_column(PG_UUID(as_uuid=True), primary_key=True, default=uuid4)
    predicted_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    stored_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    inference_duration_ms: Mapped[int] = mapped_column(BigInteger, nullable=False)
    model_version: Mapped[str] = mapped_column(Text, nullable=False)
    preprocessing_version: Mapped[str] = mapped_column(Text, nullable=False)
    artifact_sha256: Mapped[dict[str, str]] = mapped_column(
        JSONB(none_as_null=True), nullable=False
    )


def table_args(table, artifact_keys, checks, probability_groups=()):
    expressions = [
        ("duration", "inference_duration_ms >= 0"),
        ("model_version", "btrim(model_version) <> ''"),
        ("preprocessing_version", "btrim(preprocessing_version) <> ''"),
    ]
    array = "ARRAY[" + ", ".join("'" + key + "'" for key in artifact_keys) + "]"
    parts = [
        "jsonb_typeof(artifact_sha256) = 'object'",
        f"artifact_sha256 ?& {array}",
        f"artifact_sha256 - {array} = '{{}}'::jsonb",
    ]
    for key in artifact_keys:
        parts.extend([
            f"jsonb_typeof(artifact_sha256 -> '{key}') = 'string'",
            f"(artifact_sha256 ->> '{key}') ~ '^[0-9a-f]{{64}}$'",
        ])
    expressions.append(("artifacts", "(" + " AND ".join(parts) + ") IS TRUE"))
    expressions.extend(checks)
    for label, columns in probability_groups:
        expressions.append((
            label + "_range",
            " AND ".join(f"{column} BETWEEN 0 AND 1" for column in columns),
        ))
        total = "(" + " + ".join(columns) + ")"
        expressions.append((
            label + "_sum",
            f"abs({total} - 1.0) <= 0.00001 * greatest(abs({total}), 1.0)",
        ))
    return (
        *(CheckConstraint(sql, name=f"ck_{table}_{suffix}")
          for suffix, sql in expressions),
        Index(f"ix_{table}_history", text("predicted_at DESC"), text("id DESC")),
        {"schema": "public"},
    )


class FashionPrediction(PredictionFields, Base):
    __tablename__ = "fashion_predictions"

    class_index: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    label: Mapped[str] = mapped_column(Text, nullable=False)
    p_apparel: Mapped[float] = mapped_column(Double, nullable=False)
    p_accessories: Mapped[float] = mapped_column(Double, nullable=False)
    p_footwear: Mapped[float] = mapped_column(Double, nullable=False)
    p_personal_care: Mapped[float] = mapped_column(Double, nullable=False)
    image_size_bytes: Mapped[int] = mapped_column(Integer, nullable=False)
    image_format: Mapped[str] = mapped_column(Text, nullable=False)

    __table_args__ = table_args(
        __tablename__, ("vgg16",),
        [
            ("class_label",
             "(class_index = 0 AND label = 'Apparel') OR "
             "(class_index = 1 AND label = 'Accessories') OR "
             "(class_index = 2 AND label = 'Footwear') OR "
             "(class_index = 3 AND label = 'Personal Care')"),
            ("image_size", "image_size_bytes BETWEEN 1 AND 5242880"),
            ("image_format", "image_format IN ('JPEG', 'PNG')"),
        ],
        [("probabilities", ("p_apparel", "p_accessories", "p_footwear", "p_personal_care"))],
    )


class ReviewCluster(PredictionFields, Base):
    __tablename__ = "review_clusters"

    cluster: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    input_character_count: Mapped[int] = mapped_column(Integer, nullable=False)
    cleaned_character_count: Mapped[int] = mapped_column(Integer, nullable=False)

    __table_args__ = table_args(
        __tablename__, ("tfidf", "kmeans"),
        [
            ("cluster", "cluster IN (0, 1)"),
            ("input_length", "input_character_count BETWEEN 1 AND 10000"),
            ("cleaned_length", "cleaned_character_count > 0"),
        ],
    )


class PurchasePrediction(PredictionFields, Base):
    __tablename__ = "purchase_predictions"

    rf_revenue_class: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    svm_revenue_class: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    mlp_revenue_class: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    rf_probability_0: Mapped[float] = mapped_column(Double, nullable=False)
    rf_probability_1: Mapped[float] = mapped_column(Double, nullable=False)
    mlp_probability_0: Mapped[float] = mapped_column(Double, nullable=False)
    mlp_probability_1: Mapped[float] = mapped_column(Double, nullable=False)
    svm_probabilities: Mapped[dict | None] = mapped_column(
        JSONB(none_as_null=True), nullable=True
    )

    __table_args__ = table_args(
        __tablename__, ("random_forest", "svm", "mlp", "feature_columns"),
        [
            ("classes", "rf_revenue_class IN (0, 1) AND "
             "svm_revenue_class IN (0, 1) AND mlp_revenue_class IN (0, 1)"),
            ("svm_probabilities", "svm_probabilities IS NULL"),
        ],
        [
            ("rf_probabilities", ("rf_probability_0", "rf_probability_1")),
            ("mlp_probabilities", ("mlp_probability_0", "mlp_probability_1")),
        ],
    )
